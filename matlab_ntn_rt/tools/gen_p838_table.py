"""Emit +ntnrt/+atmos/p838Table.m from the Python P.838-3 arrays.

Generated rather than transcribed: the table is ~30 rows x 4 columns of
coefficients and a single wrong digit would be invisible in the results.
"""

import sys
from pathlib import Path

import numpy as np

# Import root is the directory containing Ray_Tracing/, so the
# Ray_Tracing.src.* package paths resolve however this is invoked.
sys.path.insert(0, str(Path(__file__).resolve().parents[3]))
import Ray_Tracing.src.utils.atmospheric_utils as A  # noqa: E402

OUT = Path(__file__).resolve().parent.parent / "+ntnrt" / "+atmos" / "p838Table.m"


def col(name, v):
    body = "\n".join("    " + " ".join(f"{x:.10g}" for x in v[i:i + 10])
                     + (" ..." if i + 10 < len(v) else "")
                     for i in range(0, len(v), 10))
    return f"t.{name} = [ ...\n{body}].';\n"


def main():
    f = np.asarray(A._P838_F_GHZ, float)
    parts = [
        "function t = p838Table()\n",
        "% ITU-R P.838-3 Table 1 rain coefficients (k_H, alpha_H, k_V, alpha_V).\n",
        "%\n",
        "% Generated by tools/gen_p838_table.py from atmospheric_utils._P838_* -\n",
        "% do not hand-edit. Log-log interpolation over this table reproduces the\n",
        "% tabulated points exactly, which the P.838-3 polynomial fits do not.\n\n",
        col("fGHz", f),
        col("kH", 10.0 ** np.asarray(A._P838_LOG10_KH, float)),
        col("kV", 10.0 ** np.asarray(A._P838_LOG10_KV, float)),
        col("aH", np.asarray(A._P838_AH, float)),
        col("aV", np.asarray(A._P838_AV, float)),
        "\nend\n",
    ]
    OUT.write_text("".join(parts))
    print(f"wrote {OUT} ({len(f)} rows, {f[0]}-{f[-1]} GHz)")


if __name__ == "__main__":
    main()
